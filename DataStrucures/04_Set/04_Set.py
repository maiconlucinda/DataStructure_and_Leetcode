# MUTAVEL
# SEM ORDEM
# SEM DUPLICATAS

mySet = {1,2,3}

# Adicionando um valor
mySet.add(5)

# Adicionando os valores de um iterável no meu set.
mySet.update([6, 7])

# Não da erro se não existe.
mySet.discard(2)

# Da erro se nao existir
mySet.remove(3)

# Remove e retorna um item qualquer
print(mySet.pop())

# Esvazia a lista
mySet.clear()

print(mySet)

